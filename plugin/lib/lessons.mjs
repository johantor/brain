// Lesson files: one OKF v0.2 document per lesson in <brain dir>/lessons/, the source of
// truth (#3, "Store"). brain.db's `lessons` table indexes them. Values in the
// frontmatter are written as JSON, which is valid YAML, so no YAML parser is needed.
import fs from 'node:fs';
import path from 'node:path';
import { brainDir } from './paths.mjs';

export const KINDS = ['preference', 'tool-habit', 'method-error', 'project-fact'];
const OKF_INDEX = '---\nokf_version: "0.2"\n---\n\n# brain lessons\n\nOne file per lesson. Generated by brain; edit `learned.md` once lessons load (phase 3).\n';

export function lessonsDir() {
  return path.join(brainDir(), 'lessons');
}

export function lessonFile(id) {
  return path.join(lessonsDir(), `L${id}.md`);
}

// The OKF document for one lesson. Key order follows the spec: type first.
export function render(lesson) {
  const front = {
    type: 'brain/lesson',
    title: `L${lesson.id}`,
    description: lesson.description,
    kind: lesson.kind,
    scope: lesson.scope,
    status: lesson.status,
    generated: { by: lesson.by, at: lesson.at },
    sources: lesson.sources,
    observed_with: lesson.observedWith,
  };
  if (lesson.project) front.project = lesson.project;
  const lines = Object.entries(front).map(([k, v]) => `${k}: ${JSON.stringify(v)}`);
  return `---\n${lines.join('\n')}\n---\n\n${lesson.evidence || 'No evidence text.'}\n`;
}

export function parse(text) {
  const m = /^---\n([\s\S]*?)\n---\n\n?([\s\S]*)$/.exec(text);
  if (!m) throw new Error('not a lesson file');
  const front = {};
  for (const line of m[1].split('\n')) {
    const at = line.indexOf(': ');
    if (at > 0) front[line.slice(0, at)] = JSON.parse(line.slice(at + 2));
  }
  return { front, body: m[2].trimEnd() };
}

export function writeLesson(lesson) {
  fs.mkdirSync(lessonsDir(), { recursive: true, mode: 0o700 });
  const index = path.join(lessonsDir(), 'index.md');
  if (!fs.existsSync(index)) fs.writeFileSync(index, OKF_INDEX, { mode: 0o600 });
  // Write then rename, so a reader never sees half a lesson.
  const file = lessonFile(lesson.id);
  fs.writeFileSync(`${file}.tmp`, render(lesson), { mode: 0o600 });
  fs.renameSync(`${file}.tmp`, file);
  return file;
}

// Every change to a lesson, one scrubbed line each, for review and phase 3's undo.
export function logChange(line, now = Date.now()) {
  fs.mkdirSync(brainDir(), { recursive: true, mode: 0o700 });
  fs.appendFileSync(path.join(brainDir(), 'changes.log'), `${new Date(now).toISOString()} ${line}\n`, { mode: 0o600 });
}
